<?php

namespace App\Http\Integrations\Discord\Data\Messages;

use App\Http\Integrations\Discord\Data\Users\UserData;
use App\Http\Integrations\Discord\Enums\MessageType;
use Closure;
use Spatie\LaravelData\Attributes\DataCollectionOf;
use Spatie\LaravelData\Attributes\MapName;
use Spatie\LaravelData\Attributes\Validation\BooleanType;
use Spatie\LaravelData\Attributes\Validation\IntegerType;
use Spatie\LaravelData\Attributes\Validation\Min;
use Spatie\LaravelData\Attributes\Validation\Nullable;
use Spatie\LaravelData\Attributes\Validation\StringType;
use Spatie\LaravelData\Data;
use Spatie\LaravelData\Mappers\SnakeCaseMapper;
use Spatie\LaravelData\Optional;

#[MapName(SnakeCaseMapper::class)]
final class MessageData extends Data
{
    public function __construct(
        /** @var string Message ID (snowflake) */
        #[StringType]
        public readonly string $id,

        /** @var string ID of the channel the message was sent in (snowflake) */
        #[StringType]
        public readonly string $channelId,

        /** @var UserData Author of the message */
        public readonly UserData $author,

        /** @var string Contents of the message */
        #[StringType]
        public readonly string $content,

        /** @var string ISO8601 timestamp; when this message was sent */
        #[StringType]
        public readonly string $timestamp,

        /** @var string|null ISO8601 timestamp; when this message was edited (null if never) */
        #[Nullable, StringType]
        public readonly ?string $editedTimestamp,

        /** @var bool Whether this was a TTS message */
        #[BooleanType]
        public readonly bool $tts,

        /** @var bool Whether this message mentions everyone */
        #[BooleanType]
        public readonly bool $mentionEveryone,

        /** @var array<UserData> Users specifically mentioned in the message */
        #[DataCollectionOf(UserData::class)]
        public readonly array $mentions,

        /** @var array<string> Role IDs specifically mentioned in this message */
        public readonly array $mentionRoles,

        /** @var array<AttachmentData> Any attached files not referenced in embeds or components */
        #[DataCollectionOf(AttachmentData::class)]
        public readonly array $attachments,

        /** @var array<EmbedData> Any embedded content */
        #[DataCollectionOf(EmbedData::class)]
        public readonly array $embeds,

        /** @var bool Whether this message is pinned */
        #[BooleanType]
        public readonly bool $pinned,

        /** @var MessageType Type of message */
        public readonly MessageType $type,

        /** @var string|Optional If generated by a webhook, the webhook's ID (snowflake) */
        #[StringType]
        public readonly string|Optional $webhookId,

        /** @var int|Optional Combined bitfield of MessageFlag values */
        #[IntegerType, Min(0)]
        public readonly int|Optional $flags,

        /** @var MessageReferenceData|Optional Data showing the source of a crosspost, follow add, pin, or reply */
        public readonly MessageReferenceData|Optional $messageReference,

        /** @var MessageData|Optional|null The message associated with the message_reference */
        public readonly MessageData|Optional|null $referencedMessage,

        /** @var string|Optional ID of the application if this is an interaction or app-owned webhook (snowflake) */
        #[StringType]
        public readonly string|Optional $applicationId,

        /** @var int|Optional Approximate position of the message in a thread */
        #[IntegerType, Min(0)]
        public readonly int|Optional $position,

        /** @var int|string|Optional Used for validating a message was sent */
        public readonly int|string|Optional $nonce,
    ) {}

    /**
     * Require the always-present content, edited timestamp and mentioned roles while allowing them to be empty or null, and validate the nonce as an integer or a string.
     *
     * @return array<string, array<int, string|Closure>>
     */
    public static function rules(): array
    {
        return [
            'content' => ['present', 'string'],
            'edited_timestamp' => ['present', 'nullable', 'string'],
            'mention_roles' => ['present', 'array'],
            'mention_roles.*' => ['string'],
            'nonce' => ['sometimes', function (string $attribute, mixed $value, Closure $fail): void {
                if (! is_int($value) && ! is_string($value)) {
                    $fail('The :attribute must be an integer or a string.');
                }
            }],
        ];
    }
}
